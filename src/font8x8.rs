/// Largura de avanco por caractere (a fonte usa 5 bits de padrao + 3 de
/// espacamento dentro de cada byte de 8 bits, entao avancar 8px por
/// caractere ja da um respiro natural entre letras).
pub const CHAR_WIDTH: i32 = 8;
pub const CHAR_HEIGHT: i32 = 8;

/// Desenha um caractere na posicao (x,y) do buffer, usando `put` (mesma
/// funcao de plotar pixel que o resto do compositor ja usa) -- cada bit 1
/// da linha vira um pixel de `color`, bit 0 nao desenha nada (deixa o que
/// ja estava por baixo).
pub fn draw_char(
    put: &mut dyn FnMut(i32, i32, u8),
    x: i32,
    y: i32,
    c: char,
    color: u8,
) {
    let rows = glyph_for(c.to_ascii_uppercase());
    for (row_idx, row) in rows.iter().enumerate() {
        for col in 0..8 {
            if row & (0x80 >> col) != 0 {
                put(x + col as i32, y + row_idx as i32, color);
            }
        }
    }
}

pub fn draw_text(put: &mut dyn FnMut(i32, i32, u8), x: i32, y: i32, text: &str, color: u8) {
    for (i, c) in text.chars().enumerate() {
        draw_char(put, x + i as i32 * CHAR_WIDTH, y, c, color);
    }
}
